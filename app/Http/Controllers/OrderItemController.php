<?php

namespace App\Http\Controllers;

use App\Models\Order;
use App\Models\OrderItem;
use App\Models\Meal;
use Illuminate\Http\Request;

class OrderItemController extends Controller
{
    /*
    |--------------------------------------------------------------------------
    | Add Meal To Existing Order
    |--------------------------------------------------------------------------
    */

    public function store(Request $request, Order $order)
    {
        /*
        |--------------------------------------------------------------------------
        | Validation
        |--------------------------------------------------------------------------
        */

        $validated = $request->validate([
            'meal_id' => [
                'required',
                'exists:meals,id',
            ],

            'quantity' => [
                'required',
                'integer',
                'min:1',
            ],
        ]);


        /*
        |--------------------------------------------------------------------------
        | Find Meal
        |--------------------------------------------------------------------------
        */

        $meal = Meal::where('id', $validated['meal_id'])
            ->where('is_available', true)
            ->firstOrFail();


        /*
        |--------------------------------------------------------------------------
        | Get Active Price
        |--------------------------------------------------------------------------
        |
        | If the meal has a valid discount,
        | active_price returns the discounted price.
        |
        */

        $price = $meal->active_price;


        /*
        |--------------------------------------------------------------------------
        | Check Existing Item
        |--------------------------------------------------------------------------
        */

        $existingItem = OrderItem::where('order_id', $order->id)
            ->where('meal_id', $meal->id)
            ->first();


        if ($existingItem) {

            /*
            |--------------------------------------------------------------------------
            | Increase Quantity
            |--------------------------------------------------------------------------
            */

            $existingItem->quantity += $validated['quantity'];

            /*
            |--------------------------------------------------------------------------
            | Update Price
            |--------------------------------------------------------------------------
            */

            $existingItem->price = $price;

            $existingItem->save();

        } else {

            /*
            |--------------------------------------------------------------------------
            | Create New Order Item
            |--------------------------------------------------------------------------
            */

            OrderItem::create([
                'order_id' => $order->id,
                'meal_id' => $meal->id,
                'quantity' => $validated['quantity'],
                'price' => $price,
            ]);
        }


        /*
        |--------------------------------------------------------------------------
        | Recalculate Order Total
        |--------------------------------------------------------------------------
        */

        $this->updateOrderTotal($order);


        /*
        |--------------------------------------------------------------------------
        | Return
        |--------------------------------------------------------------------------
        */

        return redirect()
            ->back()
            ->with(
                'success',
                'تمت إضافة الوجبة للطلب بنجاح!'
            );
    }


    /*
    |--------------------------------------------------------------------------
    | Update Order Item Quantity
    |--------------------------------------------------------------------------
    */

    public function update(Request $request, OrderItem $orderItem)
    {
        /*
        |--------------------------------------------------------------------------
        | Validation
        |--------------------------------------------------------------------------
        */

        $validated = $request->validate([
            'quantity' => [
                'required',
                'integer',
                'min:1',
            ],
        ]);


        /*
        |--------------------------------------------------------------------------
        | Update Quantity
        |--------------------------------------------------------------------------
        */

        $orderItem->update([
            'quantity' => $validated['quantity'],
        ]);


        /*
        |--------------------------------------------------------------------------
        | Recalculate Order Total
        |--------------------------------------------------------------------------
        */

        $this->updateOrderTotal(
            $orderItem->order
        );


        /*
        |--------------------------------------------------------------------------
        | Return
        |--------------------------------------------------------------------------
        */

        return redirect()
            ->back()
            ->with(
                'success',
                'تم تحديث الكمية بنجاح!'
            );
    }


    /*
    |--------------------------------------------------------------------------
    | Delete Order Item
    |--------------------------------------------------------------------------
    */

    public function destroy(OrderItem $orderItem)
    {
        /*
        |--------------------------------------------------------------------------
        | Get Order Before Delete
        |--------------------------------------------------------------------------
        */

        $order = $orderItem->order;


        /*
        |--------------------------------------------------------------------------
        | Delete Item
        |--------------------------------------------------------------------------
        */

        $orderItem->delete();


        /*
        |--------------------------------------------------------------------------
        | Recalculate Order Total
        |--------------------------------------------------------------------------
        */

        $this->updateOrderTotal($order);


        /*
        |--------------------------------------------------------------------------
        | Return
        |--------------------------------------------------------------------------
        */

        return redirect()
            ->back()
            ->with(
                'success',
                'تم إزالة الوجبة من الطلب!'
            );
    }


    /*
    |--------------------------------------------------------------------------
    | Update Order Total
    |--------------------------------------------------------------------------
    */

    private function updateOrderTotal(Order $order)
    {
        /*
        |--------------------------------------------------------------------------
        | Calculate Total
        |--------------------------------------------------------------------------
        */

        $total = $order->items()
            ->get()
            ->sum(function ($item) {

                return (float) $item->price
                    * (int) $item->quantity;
            });


        /*
        |--------------------------------------------------------------------------
        | Save Total
        |--------------------------------------------------------------------------
        |
        | IMPORTANT:
        | Order model uses "total", not "total_price".
        |
        */

        $order->update([
            'total' => $total,
        ]);
    }
}
